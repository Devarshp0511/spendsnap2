import React from 'react';
import { View, Text, StyleSheet, ScrollView, TouchableOpacity, Share } from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';
import { useStore } from '@/store/useStore';
import { Colors, Spacing, Radius } from '@/constants/theme';
import { formatCurrency, getCategoryLabel, getCategoryIcon, sortedCategories } from '@/utils/helpers';
import { Card, Row, Toggle, Divider } from '@/components/UI';

const RANGES = [
  {key:'today', label:'Today'},
  {key:'week',  label:'This Week'},
  {key:'month', label:'This Month'},
  {key:'year',  label:'This Year'},
] as const;

export default function ReportsScreen() {
  const { settings, updateSettings, getExpensesForPeriod, getTotalForPeriod, getByCategory } = useStore();
  const sym = settings.currencySymbol;

  const handleShare = async (rangeKey: string, rangeLabel: string) => {
    const expenses = getExpensesForPeriod(rangeKey);
    const total = getTotalForPeriod(rangeKey);
    const topCats = sortedCategories(getByCategory(expenses)).slice(0,5);
    const msg = [
      `SpendSnap — ${rangeLabel}`,
      `─────────────────`,
      `Total Spent: ${formatCurrency(total,sym)}`,
      `Transactions: ${expenses.length}`,
      ``,
      `By Category:`,
      ...topCats.map(([cat,amt])=>`  ${getCategoryLabel(cat)}: ${formatCurrency(amt,sym)}`),
      ``,
      `Generated by SpendSnap`,
    ].join('\n');
    await Share.share({message:msg});
  };

  return (
    <SafeAreaView style={styles.safe} edges={['top']}>
      <View style={styles.topbar}>
        <Text style={styles.title}>Reports</Text>
        <Text style={styles.sub}>Summaries delivered your way</Text>
      </View>
      <ScrollView style={styles.scroll} contentContainerStyle={styles.content} showsVerticalScrollIndicator={false}>

        <Text style={styles.sectionLabel}>STATEMENTS</Text>
        <View style={styles.rangeGrid}>
          {RANGES.map(r=>{
            const total = getTotalForPeriod(r.key);
            const count = getExpensesForPeriod(r.key).length;
            return (
              <Card key={r.key} style={styles.rangeCard}>
                <Text style={styles.rangeLabel}>{r.label}</Text>
                <Text style={styles.rangeTotal}>{formatCurrency(total,sym)}</Text>
                <Text style={styles.rangeSub}>{count} transactions</Text>
                <TouchableOpacity style={styles.shareBtn} onPress={()=>handleShare(r.key,r.label)}>
                  <Text style={styles.shareBtnText}>Share</Text>
                </TouchableOpacity>
              </Card>
            );
          })}
        </View>

        <Text style={[styles.sectionLabel,{marginTop:Spacing.lg}]}>AUTO-DELIVERY</Text>
        <Card style={{gap:0,padding:0,overflow:'hidden'}}>
          {[
            {icon:'💬',title:'WhatsApp digest',sub:'Every Sunday at 8 PM',key:'whatsappEnabled' as const},
            {icon:'📧',title:'Email report',sub:'1st of every month',key:'emailEnabled' as const},
            {icon:'🔔',title:'Daily digest',sub:'Every day at 9 PM',key:'dailyDigestEnabled' as const},
          ].map((item,i,arr)=>(
            <View key={item.key}>
              <Row style={styles.deliveryRow}>
                <Text style={styles.deliveryIcon}>{item.icon}</Text>
                <View style={{flex:1}}>
                  <Text style={styles.deliveryTitle}>{item.title}</Text>
                  <Text style={styles.deliverySub}>{item.sub}</Text>
                </View>
                <Toggle value={settings[item.key] as boolean} onToggle={()=>updateSettings({[item.key]:!settings[item.key]})}/>
              </Row>
              {i<arr.length-1&&<Divider style={{marginHorizontal:Spacing.lg,marginVertical:0}}/>}
            </View>
          ))}
        </Card>
      </ScrollView>
    </SafeAreaView>
  );
}

const styles = StyleSheet.create({
  safe:{flex:1,backgroundColor:Colors.bg},
  topbar:{paddingHorizontal:Spacing.lg,paddingVertical:Spacing.md,borderBottomWidth:0.5,borderBottomColor:Colors.border},
  title:{fontSize:20,fontWeight:'800',color:Colors.text,letterSpacing:-0.3},
  sub:{fontSize:12,color:Colors.text3,marginTop:2},
  scroll:{flex:1},
  content:{padding:Spacing.lg,paddingBottom:40},
  sectionLabel:{fontSize:10,color:Colors.text3,textTransform:'uppercase',letterSpacing:1.2,fontWeight:'700',marginBottom:Spacing.sm},
  rangeGrid:{flexDirection:'row',flexWrap:'wrap',gap:10},
  rangeCard:{width:'47%',gap:6},
  rangeLabel:{fontSize:12,fontWeight:'600',color:Colors.text3,textTransform:'uppercase',letterSpacing:0.5},
  rangeTotal:{fontSize:22,fontWeight:'800',color:Colors.text,letterSpacing:-0.5,marginTop:2},
  rangeSub:{fontSize:11,color:Colors.text3},
  shareBtn:{marginTop:Spacing.sm,backgroundColor:Colors.surface2,borderRadius:Radius.sm,padding:10,alignItems:'center',borderWidth:1,borderColor:Colors.border2},
  shareBtnText:{fontSize:12,fontWeight:'600',color:Colors.accent},
  deliveryRow:{padding:Spacing.lg,gap:14},
  deliveryIcon:{fontSize:18,width:32,textAlign:'center'},
  deliveryTitle:{fontSize:14,fontWeight:'600',color:Colors.text},
  deliverySub:{fontSize:11,color:Colors.text3,marginTop:2},
});
